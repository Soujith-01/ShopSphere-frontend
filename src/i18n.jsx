const LocalizationContext = createContext(null)

export function LocalizationProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem('shopsphere_lang') || 'en'
  })
  const [currency, setCurrencyState] = useState(() => {
    return localStorage.getItem('shopsphere_curr') || 'USD'
  })

  const setLanguage = (langCode) => {
    setLanguageState(langCode)
    localStorage.setItem('shopsphere_lang', langCode)
  }

  const setCurrency = (currCode) => {
    setCurrencyState(currCode)
    localStorage.setItem('shopsphere_curr', currCode)
  }

  const t = (key, defaultText = '') => {
    const dict = TRANSLATIONS[language] || TRANSLATIONS.en
    return dict[key] || TRANSLATIONS.en[key] || defaultText || key
  }

  const formatPrice = (amountInINR) => {
    const num = Number(amountInINR) || 0
    const currObj = CURRENCIES.find((c) => c.code === currency) || CURRENCIES[0]
    
    // Convert from base (INR) to selected currency
    if (currency === 'INR') {
      return `₹${num.toLocaleString('en-IN', { maximumFractionDigits: 2 })}`
    }
    if (currency === 'USD') {
      const converted = num * 0.012
      return `$${converted.toFixed(2)}`
    }
    if (currency === 'EUR') {
      const converted = num * 0.011
      return `€${converted.toFixed(2)}`
    }
    if (currency === 'GBP') {
      const converted = num * 0.0095
      return `£${converted.toFixed(2)}`
    }
    if (currency === 'JPY') {
      const converted = Math.round(num * 1.86)
      return `¥${converted.toLocaleString()}`
    }
    return `$${(num * 0.012).toFixed(2)}`
  }

  const currentLangObj = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0]
  const currentCurrObj = CURRENCIES.find((c) => c.code === currency) || CURRENCIES[0]

  return (
    <LocalizationContext.Provider
      value={{
        language,
        setLanguage,
        currentLangObj,
        currency,
        setCurrency,
        currentCurrObj,
        t,
        formatPrice,
        LANGUAGES,
        CURRENCIES,
      }}
    >
      {children}
    </LocalizationContext.Provider>
  )
}

export function useLocalization() {
  const ctx = useContext(LocalizationContext)
  if (!ctx) {
    // Fallback if rendered outside provider
    return {
      language: 'en',
      setLanguage: () => {},
      currentLangObj: LANGUAGES[0],
      currency: 'USD',
      setCurrency: () => {},
      currentCurrObj: CURRENCIES[0],
      t: (k, d) => TRANSLATIONS.en[k] || d || k,
      formatPrice: (amt) => `$${(Number(amt || 0) * 0.012).toFixed(2)}`,
      LANGUAGES,
      CURRENCIES,
    }
  }
  return ctx
}
